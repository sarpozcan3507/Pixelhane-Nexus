create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  handle text not null unique check (handle ~ '^[a-z0-9_]{3,20}$'),
  display_name text not null default 'Oyuncu' check (char_length(display_name) between 1 and 24),
  bio text not null default '' check (char_length(bio) <= 160),
  avatar text not null default '🎮',
  accent text not null default '#5cf4ff',
  status text not null default 'online' check (status in ('online','away','in_lobby','in_game','offline')),
  privacy text not null default 'public' check (privacy in ('public','friends')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.friend_requests (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  receiver_id uuid not null references public.profiles(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending','accepted','rejected')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint friend_requests_not_self check (sender_id <> receiver_id),
  constraint friend_requests_unique_pair unique(sender_id, receiver_id)
);

create table if not exists public.follows (
  follower_id uuid not null references public.profiles(id) on delete cascade,
  following_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (follower_id, following_id),
  constraint follows_not_self check (follower_id <> following_id)
);

create table if not exists public.direct_messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  receiver_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 2000),
  created_at timestamptz not null default now(),
  constraint dm_not_self check (sender_id <> receiver_id)
);
create index if not exists direct_messages_thread_idx on public.direct_messages (sender_id, receiver_id, created_at);

create table if not exists public.clubs (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.profiles(id) on delete cascade,
  name text not null check (char_length(name) between 3 and 36),
  description text not null default '' check (char_length(description) <= 180),
  is_public boolean not null default false,
  invite_code text not null unique,
  emoji text not null default '⚡',
  created_at timestamptz not null default now()
);

create table if not exists public.club_members (
  club_id uuid not null references public.clubs(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role text not null default 'member' check (role in ('owner','moderator','member')),
  joined_at timestamptz not null default now(),
  primary key (club_id, user_id)
);

create table if not exists public.club_messages (
  id bigint generated by default as identity primary key,
  club_id uuid not null references public.clubs(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 1500),
  created_at timestamptz not null default now()
);
create index if not exists club_messages_thread_idx on public.club_messages (club_id, created_at);

-- Security-definer helper avoids recursive club_members RLS evaluation.
create or replace function public.is_club_member(p_club_id uuid)
returns boolean
language sql stable security definer
set search_path = public
as $$ select exists (
  select 1 from public.club_members cm where cm.club_id = p_club_id and cm.user_id = auth.uid()
); $$;
revoke all on function public.is_club_member(uuid) from public;
grant execute on function public.is_club_member(uuid) to authenticated;

create or replace function public.join_club_with_code(p_code text)
returns jsonb
language plpgsql security definer
set search_path = public
as $$
declare c public.clubs%rowtype;
begin
  if auth.uid() is null then raise exception 'Giriş yapmalısın.'; end if;
  select * into c from public.clubs where upper(invite_code) = upper(trim(p_code)) limit 1;
  if c.id is null then raise exception 'Kulüp kodu bulunamadı.'; end if;
  insert into public.club_members(club_id,user_id,role) values(c.id,auth.uid(),'member') on conflict do nothing;
  return jsonb_build_object('id',c.id,'name',c.name,'is_public',c.is_public);
end; $$;
revoke all on function public.join_club_with_code(text) from public;
grant execute on function public.join_club_with_code(text) to authenticated;

