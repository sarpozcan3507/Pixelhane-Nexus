-- Profiles: public profiles discoverable by handle; friends-only profiles visible to accepted friends.
drop policy if exists profiles_select_discoverable on public.profiles;
create policy profiles_select_discoverable on public.profiles for select to authenticated
using (
  id = auth.uid() or privacy = 'public' or
  (privacy = 'friends' and exists (
    select 1 from public.friend_requests fr
    where fr.status = 'accepted' and
      ((fr.sender_id = auth.uid() and fr.receiver_id = profiles.id) or
       (fr.receiver_id = auth.uid() and fr.sender_id = profiles.id))
  ))
);
drop policy if exists profiles_insert_own on public.profiles;
create policy profiles_insert_own on public.profiles for insert to authenticated with check (id = auth.uid());
drop policy if exists profiles_update_own on public.profiles;
create policy profiles_update_own on public.profiles for update to authenticated using (id = auth.uid()) with check (id = auth.uid());

drop policy if exists friend_requests_select_participants on public.friend_requests;
create policy friend_requests_select_participants on public.friend_requests for select to authenticated using (sender_id = auth.uid() or receiver_id = auth.uid());
drop policy if exists friend_requests_insert_sender on public.friend_requests;
create policy friend_requests_insert_sender on public.friend_requests for insert to authenticated with check (sender_id = auth.uid() and sender_id <> receiver_id and status = 'pending');
drop policy if exists friend_requests_update_receiver on public.friend_requests;
create policy friend_requests_update_receiver on public.friend_requests for update to authenticated using (receiver_id = auth.uid()) with check (receiver_id = auth.uid());
drop policy if exists friend_requests_delete_participant on public.friend_requests;
create policy friend_requests_delete_participant on public.friend_requests for delete to authenticated using (sender_id = auth.uid() or receiver_id = auth.uid());

drop policy if exists follows_select_participant on public.follows;
create policy follows_select_participant on public.follows for select to authenticated using (follower_id = auth.uid() or following_id = auth.uid());
drop policy if exists follows_insert_self on public.follows;
create policy follows_insert_self on public.follows for insert to authenticated with check (follower_id = auth.uid() and follower_id <> following_id);
drop policy if exists follows_delete_self on public.follows;
create policy follows_delete_self on public.follows for delete to authenticated using (follower_id = auth.uid());

drop policy if exists dm_select_participants on public.direct_messages;
create policy dm_select_participants on public.direct_messages for select to authenticated using (sender_id = auth.uid() or receiver_id = auth.uid());
drop policy if exists dm_insert_sender_friend on public.direct_messages;
create policy dm_insert_sender_friend on public.direct_messages for insert to authenticated with check (
  sender_id = auth.uid() and sender_id <> receiver_id and exists (
    select 1 from public.friend_requests fr where fr.status = 'accepted' and
      ((fr.sender_id = auth.uid() and fr.receiver_id = direct_messages.receiver_id) or
       (fr.receiver_id = auth.uid() and fr.sender_id = direct_messages.receiver_id))
  )
);

drop policy if exists clubs_select_public_or_member on public.clubs;
create policy clubs_select_public_or_member on public.clubs for select to authenticated using (is_public or owner_id = auth.uid() or public.is_club_member(id));
drop policy if exists clubs_insert_owner on public.clubs;
create policy clubs_insert_owner on public.clubs for insert to authenticated with check (owner_id = auth.uid());
drop policy if exists clubs_update_owner on public.clubs;
create policy clubs_update_owner on public.clubs for update to authenticated using (owner_id = auth.uid()) with check (owner_id = auth.uid());
drop policy if exists clubs_delete_owner on public.clubs;
create policy clubs_delete_owner on public.clubs for delete to authenticated using (owner_id = auth.uid());

drop policy if exists club_members_select_member_or_self on public.club_members;
create policy club_members_select_member_or_self on public.club_members for select to authenticated using (user_id = auth.uid() or public.is_club_member(club_id));
drop policy if exists club_members_insert_owner on public.club_members;
create policy club_members_insert_owner on public.club_members for insert to authenticated with check (
  user_id = auth.uid() and exists (select 1 from public.clubs c where c.id = club_id and c.owner_id = auth.uid() )
);
drop policy if exists club_members_delete_self_or_owner on public.club_members;
create policy club_members_delete_self_or_owner on public.club_members for delete to authenticated using (
  user_id = auth.uid() or exists (select 1 from public.clubs c where c.id = club_id and c.owner_id = auth.uid())
);

drop policy if exists club_messages_select_members on public.club_messages;
create policy club_messages_select_members on public.club_messages for select to authenticated using (public.is_club_member(club_id));
drop policy if exists club_messages_insert_member on public.club_messages;
create policy club_messages_insert_member on public.club_messages for insert to authenticated with check (user_id = auth.uid() and public.is_club_member(club_id));

-- Least-privilege table access. RLS policies above still control each row.
grant select, insert, update on public.profiles to authenticated;
grant select, insert, update, delete on public.friend_requests to authenticated;
grant select, insert, delete on public.follows to authenticated;
grant select, insert on public.direct_messages to authenticated;
grant select, insert, update, delete on public.clubs to authenticated;
grant select, insert, delete on public.club_members to authenticated;
grant select, insert on public.club_messages to authenticated;
grant usage, select on all sequences in schema public to authenticated;

-- Enable realtime DB-change events for requests, DMs and club messages (idempotent).
do $$ begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'friend_requests') then
    alter publication supabase_realtime add table public.friend_requests;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'direct_messages') then
    alter publication supabase_realtime add table public.direct_messages;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'club_messages') then
    alter publication supabase_realtime add table public.club_messages;
  end if;
end $$;
